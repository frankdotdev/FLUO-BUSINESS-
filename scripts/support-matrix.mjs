// Regenerates docs/product/business-type-support.md from the code, so the document can never claim more than the product does.
import { writeFileSync } from "node:fs";
import { BUSINESS_TYPES } from "../packages/core/src/platform/business-types.ts";
import { isTypeReady, missingCapabilities, workspaceModules } from "../packages/core/src/platform/workspace.ts";
import { resolveCapabilities } from "../packages/core/src/platform/business-types.ts";

const ready = BUSINESS_TYPES.filter((t) => isTypeReady(t) && t.tier !== "later");
const rows = [...BUSINESS_TYPES].sort((a, b) => a.group.localeCompare(b.group) || a.label.localeCompare(b.label));
const need = {};
for (const t of BUSINESS_TYPES) for (const c of missingCapabilities(t)) need[c] = (need[c] ?? 0) + 1;
let md = `# Business type support (generated)\n\n**Generated by \`npm run docs:support\` from the code. Do not edit by hand.**\n\n`;
md += `${ready.length} of ${BUSINESS_TYPES.length} business types can be opened today. A type is open when every tool it starts with exists. The others appear in onboarding as they are finished.\n\n`;
md += `## What blocks the rest (types affected)\n\n| Missing tool | Types blocked |\n|---|---|\n${Object.entries(need).sort((a, b) => b[1] - a[1]).map(([c, n]) => `| ${c} | ${n} |`).join("\n")}\n\n`;
md += `## Every type\n\n| Type | Group | Can open today | Tabs the owner sees | Waiting on |\n|---|---|---|---|---|\n`;
for (const t of rows) {
  const open = isTypeReady(t) && t.tier !== "later";
  const tabs = open ? workspaceModules(t.id, resolveCapabilities(t.id)).map((m) => m.label).join(", ") : "";
  const wait = [...missingCapabilities(t), ...(t.regulation !== "none" ? ["verification review"] : [])].join(", ");
  md += `| ${t.label} | ${t.group} | ${open ? "yes" : "not yet"} | ${tabs} | ${open ? "" : wait} |\n`;
}
writeFileSync(new URL("../docs/product/business-type-support.md", import.meta.url), md);
console.log(`wrote docs/product/business-type-support.md (${ready.length} open)`);
